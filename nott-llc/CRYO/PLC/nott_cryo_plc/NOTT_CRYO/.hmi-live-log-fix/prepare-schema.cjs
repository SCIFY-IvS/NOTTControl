const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = 'C:/Users/u0149673/NOTT/NOTTControl/nott-llc/CRYO/HMI/nott_cryo_hmi/nott_cryo_hmi';
const file = 'Server/TcHmiSrv/TcHmiSrv.Config.default.json';
const original = fs.readFileSync(path.join(root, file), 'utf8');
const config = JSON.parse(original);
const previous = JSON.parse(fs.readFileSync(path.join(__dirname, '../.hmi-fan-staging', file), 'utf8'));
const name = 'ADS-NOTT_CRYO_PLC.T_NOTT_FAN_CFG';
const schema = previous.DEFINITIONS.ADS[name];
if (!schema || Object.keys(schema.properties || {}).length !== 10) throw new Error('Missing complete fan schema');
if (config.DEFINITIONS.ADS[name].properties) throw new Error('Current fan schema is no longer empty');
const nl = original.includes('\r\n') ? '\r\n' : '\n';
const oldBlock = '"' + name + '": {' + nl + '                "additionalProperties": false,' + nl + '                "type": "object"' + nl + '            }';
const newBlock = '"' + name + '": ' + JSON.stringify(schema, null, 4).replaceAll('\n', nl + '            ');
if (!original.includes(oldBlock)) throw new Error('Unexpected schema formatting');
const updated = original.replace(oldBlock, newBlock);
JSON.parse(updated);
fs.mkdirSync(path.dirname(path.join(__dirname, 'files', file)), {recursive:true});
fs.writeFileSync(path.join(__dirname, 'files', file), updated);
fs.writeFileSync(path.join(__dirname, 'manifest.json'), JSON.stringify([{file,hash:crypto.createHash('sha256').update(original).digest('hex')}], null, 2));
console.log('Restored only the ten fan configuration fields; no symbol access changes.');
